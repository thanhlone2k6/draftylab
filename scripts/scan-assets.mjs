#!/usr/bin/env node
// Scan DFL2 source folders → media-src/manifest.internal.json + docs.
// Read-only on the source tree. Re-runnable; ids are deterministic.
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import sharp from 'sharp';
import { DFL2_DIR, WEBSITE_DIR, INTERNAL_DIR, INTERNAL_MANIFEST, SECTIONS, EXPECTED_COUNTS, IMAGE_EXT, VIDEO_EXT, byName } from './lib/config.mjs';
import { probeVideo } from './lib/probe.mjs';

async function listMedia(dir) {
  let entries;
  try { entries = await fs.readdir(dir, { withFileTypes: true }); } catch { return { files: [], missing: true }; }
  const files = entries
    .filter((e) => e.isFile() && !e.name.startsWith('.'))
    .map((e) => e.name)
    .filter((n) => IMAGE_EXT.has(path.extname(n).toLowerCase()) || VIDEO_EXT.has(path.extname(n).toLowerCase()))
    .sort(byName);
  return { files, missing: false };
}

async function quickHash(file, size) {
  // Hash of size + first/last 1MB: cheap, stable enough to detect duplicates/changes.
  const fh = await fs.open(file, 'r');
  try {
    const len = Math.min(size, 1 << 20);
    const head = Buffer.alloc(len); await fh.read(head, 0, len, 0);
    const tail = Buffer.alloc(len); await fh.read(tail, 0, len, Math.max(0, size - len));
    return crypto.createHash('sha1').update(String(size)).update(head).update(tail).digest('hex').slice(0, 16);
  } finally { await fh.close(); }
}

async function describe(abs, rel, base) {
  const ext = path.extname(abs).toLowerCase();
  const stat = await fs.stat(abs);
  const common = { ...base, sourcePath: abs, sourceRel: rel, sizeBytes: stat.size, mtimeMs: Math.round(stat.mtimeMs), hash: await quickHash(abs, stat.size) };
  if (VIDEO_EXT.has(ext)) return { ...common, type: 'video', ...(await probeVideo(abs)) };
  const meta = await sharp(abs).metadata();
  const swap = (meta.orientation ?? 1) >= 5;
  return { ...common, type: 'image', width: swap ? meta.height : meta.width, height: swap ? meta.width : meta.height, format: meta.format };
}

const items = [];
const warnings = [];
for (const section of SECTIONS) {
  const groups = section.brands
    ? section.brands.map((b) => ({ dir: path.join(section.dir, b.folder), brand: b }))
    : [{ dir: section.dir, brand: null }];
  for (const g of groups) {
    const absDir = path.join(DFL2_DIR, g.dir);
    const { files, missing } = await listMedia(absDir);
    if (missing) { warnings.push(`MISSING folder: ${g.dir}`); continue; }
    let vi = 0, ii = 0;
    for (const name of files) {
      const isVideo = VIDEO_EXT.has(path.extname(name).toLowerCase());
      const n = isVideo ? ++vi : ++ii;
      const prefix = g.brand ? `${section.id}-${g.brand.id}` : section.id;
      const id = `${prefix}-${isVideo ? 'v' : 'i'}${String(n).padStart(2, '0')}`;
      items.push(await describe(path.join(absDir, name), path.join(g.dir, name), {
        id, sectionId: section.id, phase: section.phase, brandId: g.brand?.id, fileName: name,
      }));
    }
  }
}

// Duplicate detection (same size + hash).
const seen = new Map();
for (const it of items) {
  const key = `${it.sizeBytes}:${it.hash}`;
  if (seen.has(key)) { it.duplicateOf = seen.get(key); warnings.push(`DUPLICATE: ${it.sourceRel} == ${items.find((x) => x.id === seen.get(key)).sourceRel}`); }
  else seen.set(key, it.id);
}

const socialVideos = items.filter((i) => i.sectionId === 'social' && i.type === 'video').length;
const galleryVideos = items.filter((i) => i.sectionId === 'gallery' && i.type === 'video').length;
if (socialVideos !== EXPECTED_COUNTS.socialVideos) warnings.push(`COUNT: social videos = ${socialVideos}, expected ${EXPECTED_COUNTS.socialVideos}`);
if (galleryVideos !== EXPECTED_COUNTS.galleryVideos) warnings.push(`COUNT: gallery videos = ${galleryVideos}, expected ${EXPECTED_COUNTS.galleryVideos}`);

await fs.mkdir(INTERNAL_DIR, { recursive: true });
await fs.writeFile(INTERNAL_MANIFEST, JSON.stringify({ scannedAt: new Date().toISOString(), items, warnings }, null, 2));

// ---- docs (relative source paths only; no absolute machine paths) ----
const mb = (b) => (b / 1048576).toFixed(1);
const row = (i) => `| \`${i.id}\` | ${i.type} | ${i.brandId ?? '—'} | ${i.sourceRel.replaceAll('|', '\\|')} | ${i.width}×${i.height} | ${i.type === 'video' ? `${i.durationSeconds}s · ${i.codec}${i.rotation ? ` · rot ${i.rotation}` : ''}` : i.format} | ${mb(i.sizeBytes)} |`;
let md = `# Asset inventory (generated by \`npm run media:scan\`)\n\nScanned: ${new Date().toISOString()}\n\nTotals: ${items.length} files · ${items.filter((i) => i.type === 'video').length} videos · ${items.filter((i) => i.type === 'image').length} images · Social videos: **${socialVideos}** · Gallery videos: **${galleryVideos}**\n\nDimensions are display-oriented (rotation applied).\n`;
for (const s of SECTIONS) {
  const list = items.filter((i) => i.sectionId === s.id);
  md += `\n## ${s.id} (phase ${s.phase}) — ${list.length} files\n\n| id | type | brand | source (relative to DFL2) | size | detail | MB |\n|---|---|---|---|---|---|---|\n${list.map(row).join('\n')}\n`;
}
md += `\n## Warnings\n\n${warnings.map((w) => `- ${w}`).join('\n') || '- none'}\n`;
await fs.writeFile(path.join(WEBSITE_DIR, 'docs/asset-inventory.md'), md);

const roles = JSON.parse(await fs.readFile(new URL('./media-roles.json', import.meta.url), 'utf8'));
const unmapped = items.filter((i) => i.phase !== 1 && !roles[i.id]);
let um = `# Unmapped / pending assets (generated)\n\nPhase 1–2 assets are mapped through \`scripts/media-roles.json\` (labels/crops) and \`src/data/content.ts\` (stages, case studies). See [phase2-mapping.md](phase2-mapping.md) for the decisions that still need approval.\n\n## Inventoried but not mapped\n\n`;
um += unmapped.length ? `| id | section | source |\n|---|---|---|\n${unmapped.map((i) => `| \`${i.id}\` | ${i.sectionId} | ${i.sourceRel} |`).join('\n')}\n` : '- none\n';
um += `\n## Content / assets not found in DFL2\n\n- TODO: ASSETS_WEBSITE — no Website & Landing Page assets in DFL2; the section is not rendered and has no nav link until at least one real item exists.\n- TODO: Founder portrait — no clean portrait in DFL2; using V1_TEMP \`portrait-founder.webp\`.\n- TODO: Trusted By logos — none in DFL2; V1_TEMP partner logos in use.\n- TODO: CONTACT — using V1_TEMP contact (email/instagram/facebook) until confirmed.\n- TODO: Brand descriptions / official copy — not provided.\n\n## Duplicates\n\n${warnings.filter((w) => w.startsWith('DUPLICATE')).map((w) => `- ${w} → NEEDS_USER_DECISION`).join('\n') || '- none'}\n`;
await fs.writeFile(path.join(WEBSITE_DIR, 'docs/unmapped-assets.md'), um);

console.log(`Scanned ${items.length} files (social videos ${socialVideos}, gallery videos ${galleryVideos}).`);
for (const w of warnings) console.warn('WARN', w);
