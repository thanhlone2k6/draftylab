#!/usr/bin/env node
// Encode sample clips at several CRFs and measure size + VMAF (vs. source
// scaled to the same 720p frame). Writes docs/encode-quality.md and frame
// grabs to media-src/quality/. Never touches sources.
import fs from 'node:fs/promises';
import path from 'node:path';
import { INTERNAL_DIR, INTERNAL_MANIFEST, WEBSITE_DIR } from './lib/config.mjs';
import { ffmpeg, scaleFilter, videoArgs } from './lib/encode.mjs';
import { probeVideo } from './lib/probe.mjs';

const { items } = JSON.parse(await fs.readFile(INTERNAL_MANIFEST, 'utf8'));
const pick = (file) => items.find((i) => i.fileName === file);
const SAMPLES = [
  { label: 'short-form (gallery 1012.mp4)', item: pick('1012.mp4'), ss: 0, t: 20 },
  { label: 'landscape (kazaki2.mp4)', item: pick('kazaki2.mp4'), ss: 0, t: 20 },
  { label: 'long-form (winnie/inter view r7.mp4, 30s sample)', item: pick('inter view r7.mp4'), ss: 30, t: 30 },
];
const CRFS = (process.env.CRFS || '20,23,26,28').split(',').map(Number);
const outDir = path.join(INTERNAL_DIR, 'quality');
await fs.mkdir(outDir, { recursive: true });

const rows = [];
for (const s of SAMPLES) {
  if (!s.item) { console.warn('missing sample', s.label); continue; }
  const ref = path.join(outDir, `${s.item.id}-ref.mkv`);
  // Lossless-ish reference at the same 720p frame so VMAF compares like for like.
  await ffmpeg(['-ss', String(s.ss), '-t', String(s.t), '-i', s.item.sourcePath, '-vf', scaleFilter(720), '-c:v', 'libx264', '-crf', '0', '-preset', 'ultrafast', '-an', ref]);
  for (const crf of CRFS) {
    const out = path.join(outDir, `${s.item.id}-crf${crf}.mp4`);
    await ffmpeg(['-ss', String(s.ss), '-t', String(s.t), '-i', s.item.sourcePath, ...videoArgs({ crf, maxrate: '8M', bufsize: '16M' }), out]);
    const log = await ffmpeg(['-i', out, '-i', ref, '-lavfi', '[0:v]setpts=PTS-STARTPTS[d];[1:v]setpts=PTS-STARTPTS[r];[d][r]libvmaf=n_threads=8', '-f', 'null', '-'], { quiet: false });
    const vmaf = Number((log.match(/VMAF score: ([\d.]+)/) || [])[1]);
    const p = await probeVideo(out);
    await ffmpeg(['-ss', String(Math.min(5, s.t / 2)), '-i', out, '-frames:v', '1', path.join(outDir, `${s.item.id}-crf${crf}.png`)]);
    const kbps = Math.round((p.sizeBytes * 8) / p.durationSeconds / 1000);
    rows.push({ label: s.label, crf, vmaf, kbps, mbPerMin: ((p.sizeBytes / 1048576) / p.durationSeconds * 60).toFixed(1) });
    console.log(s.label, 'crf', crf, 'vmaf', vmaf, 'kbps', kbps);
  }
}

let md = `# Encode quality test (generated by \`npm run media:quality\`)\n\nDate: ${new Date().toISOString()}\n\nSettings: libx264 \`-preset slow\`, short edge ≤720, \`-maxrate 8M\` (test only), AAC 128k, \`+faststart\`. VMAF vs. the source scaled to the same 720p frame (≥93 ≈ visually transparent on phones, ≥90 good).\n\n| sample | CRF | VMAF | video+audio kbps | MB / min |\n|---|---|---|---|---|\n`;
md += rows.map((r) => `| ${r.label} | ${r.crf} | ${r.vmaf.toFixed(2)} | ${r.kbps} | ${r.mbPerMin} |`).join('\n');
md += `\n\nFrame grabs: \`media-src/quality/*.png\` (local only, not committed).\n\nChosen presets: see \`scripts/encode-presets.json\` and the reasoning below.\n`;
await fs.writeFile(path.join(WEBSITE_DIR, 'docs/encode-quality.md'), md);
